#!/usr/bin/env python3
"""Write the full catalog into README.md, between CATALOG_BEGIN and CATALOG_END: every agent
(role) by pack and every library entry (ECC skills, commands, rules) by pack, from the plugin's
own files, so the README never drifts from what ships.

    python3 tools/readme_catalog.py          rewrite the block
    python3 tools/readme_catalog.py --check  exit 1 when the block is out of date (the tests run it)
"""
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, ".."))
sys.path.insert(0, os.path.join(ROOT, "skills", "team-workflow", "scripts"))
import library  # noqa: E402
import roles  # noqa: E402

README = os.path.join(ROOT, "README.md")
CATALOG_BEGIN = "<!-- catalog:begin (generated by tools/readme_catalog.py: do not edit by hand) -->"
CATALOG_END = "<!-- catalog:end -->"
PACK_ORDER = ("core", "frameworks", "quality", "planning", "ml", "harness", "gan", "opensource",
              "network", "domains", "ops", "growth")


def short(text, limit=160):
    """The first sentence of a description, cut at limit, safe inside a table cell."""
    text = re.sub(r"\s+", " ", text or "").strip()
    text = re.sub(r"^Use this agent (?:to |for )?", "", text)
    text = text[:1].upper() + text[1:]
    first = re.split(r"(?<=[.!?])\s", text, maxsplit=1)[0]
    if len(first) > limit:
        first = first[:limit - 1].rsplit(" ", 1)[0] + "…"
    return first.replace("|", "\\|")


def version():
    with open(os.path.join(ROOT, ".claude-plugin", "plugin.json"), encoding="utf-8") as f:
        return json.load(f)["version"]


def agents_block():
    catalog = roles.catalog()
    packs = {}
    for role, info in catalog.items():
        packs.setdefault(info["pack"], []).append(role)
    languages = sorted(p for p in packs if p in roles.languages())
    order = [p for p in PACK_ORDER if p in packs] + sorted(
        p for p in packs if p not in PACK_ORDER and p not in languages)
    out = [f"### Tutti gli agenti ({len(catalog)})", "",
           "`ECC` = importato da Everything Claude Code. Accendi un pack con "
           "`/team-workflow:agents enable <pack>` (il core e' sempre acceso).", ""]
    for pack in order:
        out += [f"<details><summary><b>{pack}</b> ({len(packs[pack])})</summary>", "",
                "| Agente | Cosa fa |", "|---|---|"]
        for role in sorted(packs[pack]):
            meta, _ = roles.parse(roles.read(catalog[role]))
            mark = " `ECC`" if meta.get("source", "").startswith("ECC") else ""
            out.append(f"| `{role}`{mark} | {short(meta.get('description'))} |")
        out += ["", "</details>", ""]
    out += [f"<details><summary><b>linguaggi</b> ({len(languages)} pack, "
            f"{sum(len(packs[p]) for p in languages)} agenti)</summary>", "",
            "| Pack | Agenti | Cosa controllano |", "|---|---|---|"]
    for slug in languages:
        meta, _ = roles.languages()[slug]
        out.append(f"| `{slug}` | `{slug}-reviewer`, `{slug}-build-fixer` | "
                   f"{short(meta.get('language', slug) + ': ' + meta.get('focus', ''))} |")
    return out + ["", "</details>", ""]


def library_block():
    data, found = library.index(), library.entries()
    src = data["source"]
    kinds = {k: sum(e["kind"] == k for e in found.values()) for k in ("skill", "command", "rule")}
    out = [f"### Tutta la libreria ({len(found)}: {kinds['skill']} skill, {kinds['command']} "
           f"comandi, {kinds['rule']} set di regole)", "",
           f"Da Everything Claude Code {src.get('version', '')} (MIT). Cerca con "
           "`/team-workflow:library search <parole>`, installa con `library enable <id|pack>`. "
           "`ECC runtime` = chiama gli script di ECC: serve `addons add ecc`.", ""]
    for pack, about in data["packs"].items():
        mine = sorted((e for e in found.values() if e["pack"] == pack), key=lambda e: e["id"])
        out += [f"<details><summary><b>{pack}</b> ({len(mine)}): {short(about, 100)}</summary>", "",
                "| Voce | Tipo | Cosa fa |", "|---|---|---|"]
        for e in mine:
            note = " (`ECC runtime`)" if e.get("runtime") else ""
            out.append(f"| `{e['id']}` | {e['kind']} | {short(e['description'])}{note} |")
        out += ["", "</details>", ""]
    return out


def block():
    lines = [CATALOG_BEGIN, "", f"## Catalogo completo (versione {version()})", ""]
    lines += agents_block() + library_block()
    return "\n".join(lines + [CATALOG_END])


def render(text):
    new = block()
    if CATALOG_BEGIN in text:
        start, end = text.index(CATALOG_BEGIN), text.index(CATALOG_END) + len(CATALOG_END)
        return text[:start] + new + text[end:]
    marker = "\n## Sviluppo"
    return text.replace(marker, "\n" + new + "\n" + marker, 1)


def main(argv):
    with open(README, encoding="utf-8") as f:
        text = f.read()
    new = render(text)
    if "--check" in argv:
        if new != text:
            raise SystemExit("README.md catalog is out of date: python3 tools/readme_catalog.py")
        return
    with open(README, "w", encoding="utf-8", newline="\n") as f:
        f.write(new)
    print("README.md catalog written")


if __name__ == "__main__":
    main(sys.argv[1:])
